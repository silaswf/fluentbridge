export type JapaneseScriptMode = 'standard' | 'kana';

const STORAGE_KEY = 'fluentbridge_ja_script_mode';

export function loadJapaneseScriptMode(): JapaneseScriptMode {
  try {
    if (typeof window === 'undefined') return 'standard';
    const v = window.localStorage.getItem(STORAGE_KEY);
    return v === 'kana' ? 'kana' : 'standard';
  } catch {
    return 'standard';
  }
}

export function saveJapaneseScriptMode(mode: JapaneseScriptMode): void {
  try {
    if (typeof window === 'undefined') return;
    window.localStorage.setItem(STORAGE_KEY, mode);
  } catch {
    // ignore storage quota errors
  }
}

export function extractKanjiChars(text: string): string[] {
  const matches = text.match(/[\u4E00-\u9FFF]/g);
  if (!matches) return [];
  return Array.from(new Set(matches));
}

